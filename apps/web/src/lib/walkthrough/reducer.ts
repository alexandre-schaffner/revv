// The walkthrough store's pure core: the per-PR entry, how streamed events and
// REST snapshots fold into it, and the UI state it projects to. No runes, so
// it is unit-tested directly (walkthrough-reducer.test.ts).

import {
  type Activity,
  type ActivityResult,
  RATING_AXES,
  type RiskLevel,
  type Walkthrough,
  type WalkthroughBlock,
  type WalkthroughEndReason,
  type WalkthroughIssue,
  type WalkthroughLead,
  type WalkthroughLifecyclePhase,
  type WalkthroughMode,
  type WalkthroughPipelinePhase,
  type WalkthroughRating,
  type WalkthroughSemanticStep,
  type WalkthroughStatus,
  type WalkthroughStreamEvent,
  type WalkthroughTokenUsage,
  ZERO_TOKEN_USAGE,
} from "@revv/shared";

/**
 * The live "Reviewing…" feed: model reasoning and exploration tool calls in
 * arrival order. Live generation only; never persisted.
 */
export type WalkthroughTimelineEntry =
  | { kind: "thought"; id: string; text: string }
  | { kind: "exploration"; id: string; activity: Activity };

export interface WalkthroughEntry {
  mode: WalkthroughMode;
  semanticSteps: WalkthroughSemanticStep[];
  blocks: WalkthroughBlock[];
  summary: string | null;
  riskLevel: RiskLevel | null;
  /** Model the run actually launched with; null until a walkthrough has started. Lets the selector name what "Auto" resolved to. */
  modelUsed: string | null;
  sentiment: string | null;
  lastCompletedPhase: WalkthroughPipelinePhase;
  isStreaming: boolean;
  streamError: string | null;
  /** Why the run behind `streamError` ended, when the server said. */
  streamEndReason: WalkthroughEndReason | null;
  walkthroughId: string | null;
  doneReceived: boolean;
  superseded: boolean;
  historical: boolean;
  explorationSteps: Activity[];
  /** Tool outputs by provider `callId`, for each exploration pill's peek. Live generation only. */
  explorationResults: Record<string, ActivityResult>;
  /** Tool inputs the agent supplied after the call, by `callId`. Live generation only. */
  explorationInputs: Record<string, unknown>;
  timeline: WalkthroughTimelineEntry[];
  issues: WalkthroughIssue[];
  ratings: WalkthroughRating[];
  /**
   * The first-pass leads this walkthrough's agent was handed, with its
   * verdicts. Null when nothing recorded them (an older or imported row):
   * the UI then infers outcomes from where the issues sit.
   */
  leads: WalkthroughLead[] | null;
  phase: WalkthroughLifecyclePhase;
  phaseMessage: string;
  streamStartedAt: number | null;
  liveGeneration: boolean;
  tokenUsage: WalkthroughTokenUsage;
  source: "local" | "remote";
  /** "Generated by @alice"; null when the row predates attribution. */
  generatedBy: NonNullable<Walkthrough["generatedBy"]> | null;
  /** The provider config the walkthrough was generated with, for the footer. */
  providerConfig: NonNullable<Walkthrough["providerConfig"]> | null;
}

/** An entry for a run that is starting: streaming, nothing written yet. */
export function startingEntry(
  mode: WalkthroughMode,
  phaseMessage: string,
  now = Date.now(),
): WalkthroughEntry {
  return {
    mode,
    semanticSteps: [],
    blocks: [],
    summary: null,
    riskLevel: null,
    modelUsed: null,
    sentiment: null,
    lastCompletedPhase: "none",
    isStreaming: true,
    streamError: null,
    streamEndReason: null,
    walkthroughId: null,
    doneReceived: false,
    superseded: false,
    historical: false,
    explorationSteps: [],
    explorationResults: {},
    explorationInputs: {},
    timeline: [],
    issues: [],
    ratings: [],
    leads: null,
    phase: "connecting",
    phaseMessage,
    streamStartedAt: now,
    liveGeneration: false,
    tokenUsage: { ...ZERO_TOKEN_USAGE },
    source: "local",
    generatedBy: null,
    providerConfig: null,
  };
}

/** An entry waiting on its first snapshot: not streaming, nothing known. */
export function idleEntry(mode: WalkthroughMode): WalkthroughEntry {
  return { ...startingEntry(mode, ""), isStreaming: false, streamStartedAt: null };
}

/** Summary, at least one block and every rating axis: nothing left to write. */
export function hasAllContent(entry: WalkthroughEntry): boolean {
  return (
    entry.summary !== null && entry.blocks.length > 0 && entry.ratings.length >= RATING_AXES.length
  );
}

/** A finished, error-free walkthrough holding all its content; a REST read can't add to it. */
export function isSettledComplete(entry: WalkthroughEntry): boolean {
  return entry.doneReceived && entry.streamError === null && hasAllContent(entry);
}

/** The entry with everything a walkthrough authored dropped; lifecycle fields kept. */
function withoutContent(entry: WalkthroughEntry): WalkthroughEntry {
  const {
    mode,
    isStreaming,
    streamError,
    walkthroughId,
    doneReceived,
    superseded,
    historical,
    leads,
    phase,
    phaseMessage,
    liveGeneration,
  } = entry;
  return {
    ...idleEntry(mode),
    isStreaming,
    streamError,
    walkthroughId,
    doneReceived,
    superseded,
    historical,
    leads,
    phase,
    phaseMessage,
    liveGeneration,
  };
}

function upsertBy<T, K>(items: readonly T[], item: T, key: (t: T) => K): T[] {
  const id = key(item);
  const index = items.findIndex((existing) => key(existing) === id);
  return index >= 0
    ? items.map((existing, i) => (i === index ? item : existing))
    : [...items, item];
}

function finish(
  entry: WalkthroughEntry,
  walkthroughId: string,
  tokenUsage: WalkthroughTokenUsage,
): void {
  entry.walkthroughId = walkthroughId;
  entry.doneReceived = true;
  entry.isStreaming = false;
  entry.tokenUsage = tokenUsage;
  if (hasAllContent(entry)) entry.lastCompletedPhase = "D";
}

function fail(
  entry: WalkthroughEntry,
  failure: { reason: WalkthroughEndReason; message: string },
): void {
  entry.isStreaming = false;
  // A user-initiated stop: the entry falls through to resumable or idle.
  const stopped = failure.reason === "cancelled";
  entry.streamError = stopped ? null : failure.message;
  entry.streamEndReason = stopped ? null : failure.reason;
}

/** Fold streamed events into `entry`. Returns a new entry; `entry` is untouched. */
export function applyEvents(
  entry: WalkthroughEntry,
  events: readonly WalkthroughStreamEvent[],
  now = Date.now(),
): WalkthroughEntry {
  let next: WalkthroughEntry = { ...entry };
  let blocks: WalkthroughBlock[] | null = null;

  for (const event of events) {
    switch (event.type) {
      case "summary":
        next.summary = event.data.summary;
        next.riskLevel = event.data.riskLevel;
        break;
      case "sentiment":
        next.sentiment = event.data.sentiment;
        break;
      case "semantic-step":
        next.semanticSteps = upsertBy(
          next.semanticSteps,
          event.data,
          (s) => s.semanticStepIndex,
        ).sort((a, b) => a.semanticStepIndex - b.semanticStepIndex);
        break;
      case "block":
        blocks = upsertBy(blocks ?? next.blocks, event.data, (b) => b.id);
        break;
      case "lifecycle:complete":
        if (blocks) {
          next.blocks = blocks.sort((a, b) => a.order - b.order);
          blocks = null;
        }
        finish(next, event.data.walkthroughId, event.data.tokenUsage);
        break;
      case "usage":
        next.tokenUsage = event.data.tokenUsage;
        break;
      case "exploration":
        next.explorationSteps = [...next.explorationSteps, event.data];
        next.timeline = [
          ...next.timeline,
          { kind: "exploration", id: `exp-${next.timeline.length}`, activity: event.data },
        ];
        break;
      case "exploration-result":
        next.explorationResults = { ...next.explorationResults, [event.data.callId]: event.data };
        break;
      case "exploration-input":
        next.explorationInputs = {
          ...next.explorationInputs,
          [event.data.callId]: event.data.payload,
        };
        break;
      case "thought": {
        // The model streams hundreds of deltas per burst: extend the current
        // run of thought until a tool call breaks it.
        const last = next.timeline.at(-1);
        next.timeline =
          last?.kind === "thought"
            ? [...next.timeline.slice(0, -1), { ...last, text: last.text + event.data.text }]
            : [
                ...next.timeline,
                { kind: "thought", id: `thought-${next.timeline.length}`, text: event.data.text },
              ];
        break;
      }
      case "issue":
        next.issues = upsertBy(next.issues, event.data, (i) => i.id);
        break;
      case "leads":
        next.leads = event.data.leads;
        break;
      case "lead":
        next.leads = upsertBy(next.leads ?? [], event.data, (l) => l.id);
        break;
      case "rating":
        next.ratings = upsertBy(next.ratings, event.data, (r) => r.axis);
        break;
      case "phase":
        next.phase = event.data.phase;
        next.phaseMessage = event.data.message;
        if (event.data.phase !== "connecting") next.liveGeneration = true;
        break;
      case "phase:advanced":
        next.lastCompletedPhase = event.data.lastCompletedPhase;
        next.liveGeneration = true;
        break;
      case "lifecycle:error":
        fail(next, event.data);
        break;
      case "lifecycle:edited":
        // The edit's content arrives as its own envelope.
        break;
      case "block:deleted":
        blocks = (blocks ?? next.blocks).filter((b) => b.id !== event.data.id);
        break;
      case "rating:deleted":
        next.ratings = next.ratings.filter((r) => r.axis !== event.data.axis);
        break;
      case "issue:deleted":
        next.issues = next.issues.filter((i) => i.id !== event.data.id);
        break;
      case "semantic-step:deleted": {
        const index = event.data.semanticStepIndex;
        next.semanticSteps = next.semanticSteps.filter((s) => s.semanticStepIndex !== index);
        blocks = (blocks ?? next.blocks).filter((b) => b.semanticStepIndex !== index);
        break;
      }
      case "lifecycle:started":
        if (next.walkthroughId !== event.data.walkthroughId) {
          // Lead ids repeat across runs; this run's arrive as `leads`.
          next.leads = null;
          // A run this page didn't start (an external agent's
          // `request_walkthrough`) replaces the review on screen rather than
          // merging into it.
          if (next.walkthroughId !== null) {
            next = withoutContent(next);
            blocks = null;
          }
        }
        next.walkthroughId = event.data.walkthroughId;
        next.mode = event.data.mode ?? next.mode;
        // Present only when the orchestrator assigned the tier at job start.
        if (event.data.riskLevel) next.riskLevel = event.data.riskLevel;
        if (event.data.modelUsed) next.modelUsed = event.data.modelUsed;
        next.doneReceived = false;
        next.streamError = null;
        next.streamEndReason = null;
        next.superseded = false;
        next.historical = false;
        next.liveGeneration = true;
        next.phase = "connecting";
        next.phaseMessage = "Starting walkthrough…";
        if (next.streamStartedAt === null) next.streamStartedAt = now;
        next.isStreaming = true;
        break;
      case "lifecycle:cache-hit":
        if (event.data.source === "remote") next.source = "remote";
        next.walkthroughId = event.data.walkthroughId;
        break;
      case "lifecycle:superseded":
        next.superseded = true;
        next.isStreaming = false;
        break;
    }
  }

  if (blocks) next.blocks = blocks.sort((a, b) => a.order - b.order);
  return next;
}

// ── REST snapshots ──────────────────────────────────────────────────────────

/** A found walkthrough from `/current` or `/report/:id`. */
export interface WalkthroughSnapshot {
  status: WalkthroughStatus;
  walkthrough: Walkthrough;
  seqAt?: number;
  stale?: boolean;
  historical?: boolean;
}

const PHASE_RANK: Record<WalkthroughPipelinePhase, number> = { none: 0, A: 1, B: 2, C: 3, D: 4 };

function mergeKeyed<T, K>(snapshot: readonly T[], live: readonly T[], key: (t: T) => K): T[] {
  const byKey = new Map<K, T>();
  for (const item of snapshot) byKey.set(key(item), item);
  for (const item of live) byKey.set(key(item), item);
  return [...byKey.values()];
}

/**
 * Fold a REST snapshot into the entry. `previous` holds whatever the SSE
 * delivered while the request was in flight, which is newer than the
 * snapshot: its scalars win when set and its items overlay the snapshot's.
 * Returns a new entry; `previous` is untouched.
 */
export function mergeSnapshot(
  previous: WalkthroughEntry | undefined,
  { status, walkthrough: wt, stale, historical }: WalkthroughSnapshot,
  now = Date.now(),
): WalkthroughEntry {
  const isGenerating = status === "generating";
  const isError = status === "error";
  const isHistorical = historical === true && !isGenerating;
  const entry: WalkthroughEntry = previous ? { ...previous } : startingEntry("reviewer", "", now);
  entry.mode = wt.mode;

  const hasRealSummary = wt.summary !== "";
  entry.summary = entry.summary ?? (hasRealSummary ? wt.summary : null);
  // A generating row with no summary still carries the schema default `'low'`;
  // the tier is real once the overview or the risk pass has landed.
  const hasRealRisk = hasRealSummary || wt.riskConfidence != null;
  entry.riskLevel = entry.riskLevel ?? (hasRealRisk ? wt.riskLevel : null);
  entry.modelUsed = entry.modelUsed ?? wt.modelUsed;
  entry.sentiment = entry.sentiment ?? wt.sentiment ?? null;

  if (PHASE_RANK[wt.lastCompletedPhase] > PHASE_RANK[entry.lastCompletedPhase]) {
    entry.lastCompletedPhase = wt.lastCompletedPhase;
  }

  entry.semanticSteps = mergeKeyed(
    wt.semanticSteps,
    entry.semanticSteps,
    (s) => s.semanticStepIndex,
  ).sort((a, b) => a.semanticStepIndex - b.semanticStepIndex);
  entry.blocks = mergeKeyed(wt.blocks, entry.blocks, (b) => b.id).sort((a, b) => a.order - b.order);
  entry.issues = mergeKeyed(wt.issues, entry.issues, (i) => i.id);
  entry.ratings = mergeKeyed(wt.ratings, entry.ratings, (r) => r.axis);

  // Lead ids (`L1`…) repeat across runs: the live verdicts only overlay the
  // snapshot of the same walkthrough.
  if (wt.leads != null) {
    entry.leads = mergeKeyed(
      wt.leads,
      entry.walkthroughId === wt.id ? (entry.leads ?? []) : [],
      (l) => l.id,
    );
  } else if (entry.walkthroughId !== wt.id) {
    entry.leads = null;
  }

  entry.walkthroughId = wt.id;
  entry.doneReceived = !isGenerating && !isError;
  entry.isStreaming = isGenerating;
  entry.tokenUsage = wt.tokenUsage;
  // A row the user stopped reads as resumable, as it does live.
  const failed = isError && !isHistorical && wt.endReason !== "cancelled";
  entry.streamError = failed
    ? (wt.errorMessage ?? "Walkthrough generation failed. Resume or regenerate to retry.")
    : null;
  entry.streamEndReason = failed ? (wt.endReason ?? null) : null;
  // A generating row is never shown as outdated: `stale` compares head SHAs
  // that can disagree while a sync is in flight. A really stale row gets
  // superseded server-side, with `lifecycle:superseded` for this id.
  entry.superseded = !isGenerating && stale === true;
  entry.historical = isHistorical;
  entry.phase = isGenerating ? "writing" : "finishing";
  entry.phaseMessage = isGenerating ? "Resuming walkthrough…" : "Complete";
  entry.liveGeneration = isGenerating;
  entry.generatedBy = wt.generatedBy ?? entry.generatedBy;
  entry.providerConfig = wt.providerConfig ?? entry.providerConfig;
  if (isGenerating) entry.streamStartedAt = now;
  return entry;
}

// ── UI state ────────────────────────────────────────────────────────────────

export type WalkthroughUiState =
  | { kind: "absent" }
  | { kind: "idle" }
  | { kind: "streaming"; phase: WalkthroughLifecyclePhase }
  | { kind: "resumable"; lastPhase: WalkthroughPipelinePhase }
  | { kind: "complete" }
  | { kind: "complete-stale" }
  | { kind: "error-empty"; message: string }
  | { kind: "error-partial"; message: string; lastPhase: WalkthroughPipelinePhase };

export function walkthroughUiState(entry: WalkthroughEntry | undefined): WalkthroughUiState {
  if (!entry) return { kind: "absent" };
  if (entry.isStreaming) return { kind: "streaming", phase: entry.phase };
  if (entry.superseded) return { kind: "complete-stale" };
  const hasPartial = entry.summary !== null || entry.blocks.length > 0;
  if (entry.streamError) {
    return hasPartial
      ? { kind: "error-partial", message: entry.streamError, lastPhase: entry.lastCompletedPhase }
      : { kind: "error-empty", message: entry.streamError };
  }
  if (entry.historical || (entry.doneReceived && entry.lastCompletedPhase === "D")) {
    return { kind: "complete" };
  }
  if (hasPartial) return { kind: "resumable", lastPhase: entry.lastCompletedPhase };
  return { kind: "idle" };
}
